struct StudentHomeworkHelpView: View {
    var body: some View {
        List {
            Section("先生から届くもの") {
                Text("先生から、新着通知ファイルと宿題JSONファイルが届きます。")
                Text("AirDrop、メール、LINEなどで送られてくることがあります。")
            }

            Section("1. ファイルを受け取る") {
                Text("届いた .json ファイル名をタップします。")
                Text("iPhoneの「Files」アプリで保存先(iCloudや「このiPhone内)を選びます。")
                Text("新着通知ファイルと宿題JSONファイルの両方を保存してください。")
            }

            Section("2. 新着通知ファイルを保存する") {
                Text("新着通知ファイルは、前回の通知ファイルに上書きして保存します。")
                Text("保存先で同じ名前のファイルがある場合は、置き換えてください。")
                Text("このファイルは、HOMEの「新着確認」で使います。")
            }

            Section("3. 宿題JSONを保存する") {
                Text("宿題JSONは、その回の日付が入ったファイルを保存します。")
                Text("新着通知に書かれている日付と同じ宿題JSONを選んでください。")
                Text("保存するときは「移動」を押して、ファイルアプリ内に入れてください。")
            }

            Section("4. アプリで新着確認する") {
                Text("Words’ Forestを開き、HOMEの「新着確認」を押します。")
                Text("ファイルアプリから、新着通知ファイルを選びます。")
                Text("新しい宿題があると、HOMEに表示されます。")
            }

            Section("5. 宿題を取得する") {
                Text("HOMEの「宿題取得」を押します。")
                Text("ファイルアプリから、通知と同じ日付の宿題JSONを選びます。")
                Text("取り込みが終わると、「今回分へ」から宿題を開けます。")
            }

            Section("気をつけること") {
                Text("新着通知ファイルと宿題JSONの日付が違うと、正しく表示されないことがあります。")
                Text("宿題JSONは、その回の日付のファイルを選んでください。")
                Text("同じ宿題をもう一度取り込むと、取得済みとして扱われます。")
            }
        }
        .navigationTitle("宿題の受け取り方")
    }
}

struct TeacherHomeworkHelpView: View {
    var body: some View {
        List {
            Section("先生が用意するもの") {
                Text("先生は、宿題JSONファイルと新着通知ファイルを作ります。")
                Text("宿題JSONには、その回に出す単語セットが入ります。")
                Text("新着通知ファイルには、宿題の日付・品詞・語数・宿題JSONのIDが入ります。")
            }

            Section("1. TeacherLockを解除する") {
                Text("HOMEのTeacherボタンから先生用ロックを解除します。")
                Text("ロックを解除すると、宿題編集・書き出し・通知作成などのボタンが表示されます。")
            }

            Section("2. 宿題セットを編集する") {
                Text("「宿題編集」から、その回に出したい単語を選びます。")
                Text("必須に入れた単語は優先して出題されます。")
                Text("足りない分は、アプリ内の単語カードから自動で補充されます。")
                Text("途中で閉じても、選んだ必須単語は下書きとして残ります。")
            }

            Section("3. 宿題JSONを書き出す") {
                Text("「書き出し」から、その回の宿題JSONを書き出します。")
                Text("このファイルが、生徒が実際に取り込む宿題セットです。")
                Text("日付と品詞ペアを確認してから書き出してください。")
            }

            Section("4. 新着通知ファイルを作る") {
                Text("「通知」を押して、新しい宿題があることを知らせるファイルを作ります。")
                Text("宿題IDには、宿題JSONの id と同じ文字列を入れます。")
                Text("例：2026-05-24-draft-pair1")
                Text("ファイル名に .json が付いていても、ID欄には .json を付ける必要はありません。")
                Text("pair0 は 名詞＋形容詞、pair1 は 動詞＋副詞を表します。")
                Text("日付・品詞ペア・語数を確認してから、「通知ファイルを書き出す」を押します。")
                Text("このIDがずれると、生徒側で新着表示が残ることがあります。")
            }

            Section("5. 生徒に送る") {
                Text("生徒には、宿題JSONファイルと新着通知ファイルの両方を送ります。")
                Text("AirDrop、メール、LINEなどで送ることができます。")
                Text("生徒には、届いた .json ファイルをファイルアプリに保存してもらいます。")
            }

            Section("6. 生徒側の流れ") {
                Text("生徒はHOMEで「新着確認」を押し、新着通知ファイルを選びます。")
                Text("その後「宿題取得」を押し、同じ日付の宿題JSONを選びます。")
                Text("取り込みが完了すると、「今回分へ」から宿題を開けます。")
            }

            Section("大切な注意") {
                Text("新着通知ファイルと宿題JSONの日付・IDが一致している必要があります。")
                Text("通知だけ新しくして宿題JSONが古いままだと、正しく取得できないことがあります。")
                Text("同じ宿題JSONをもう一度取り込むと、取得済みとして扱われます。")
            }

            Section("困ったとき") {
                Text("新着表示が消えないときは、通知ファイルと宿題JSONのIDが一致しているか確認してください。")
                Text("宿題が開けないときは、通知と同じ日付の宿題JSONを選んでいるか確認してください。")
                Text("必要な場合は、TeacherLock解除後に宿題修復を使います。")
            }
            
            Section("単語カードを作り置きする") {
                Text("品詞ページの「＋」から、単語カードを追加できます。")
                Text("意味・例文・ノートを先に作っておくと、あとで宿題編集からそのカードを選べます。")
                Text("宿題編集は、作っておいたカードを組み合わせて宿題セットにする場所です。")
            }

            Section("その他品詞について") {
                Text("その他品詞は、自習用の単語カードです。")
                Text("現在の宿題セットには含まれません。")
                Text("生徒に使わせたいその他品詞は、あらかじめアプリ内に用意しておきます。")
            }
        }
        .navigationTitle("先生向け：宿題の出し方")
    }
}
